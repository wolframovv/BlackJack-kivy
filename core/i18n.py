class I18n:
    def __init__(self, language='russian'):
        self.language = language if language in TRANSLATIONS else 'russian'

    def set_language(self, language):
        if language in TRANSLATIONS:
            self.language = language

    def next_language(self):
        index = LANGUAGES.index(self.language)
        self.language = LANGUAGES[(index + 1) % len(LANGUAGES)]
        return self.language

    @property
    def short(self):
        return 'RU' if self.language == 'russian' else 'EN'

    def t(self, key):
        return TRANSLATIONS[self.language].get(key, key)


i18n = I18n()
t = i18n.t


def duration_text(seconds):
    """Время в виде «23 ч 59 мин» (минуты округляются вверх)."""
    minutes_total = (max(0, int(seconds)) + 59) // 60
    hours, minutes = divmod(minutes_total, 60)
    parts = []
    if hours:
        parts.append(f"{hours} {t('hours_short')}")
    if minutes:
        parts.append(f"{minutes} {t('minutes_short')}")
    return ' '.join(parts) if parts else t('less_than_minute')
